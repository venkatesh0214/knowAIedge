import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source=fs.readFileSync('app/repository-data.ts','utf8');
const seed=JSON.parse(fs.readFileSync('app/repository-seed.json','utf8'));
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const context={exports:{},require:name=>name==='cloudflare:workers'?{env:{}}:name==='./repository-seed.json'?{...seed,default:seed}:(()=>{throw Error(name)})(),console,Date,Math,Map,Set};
vm.runInNewContext(compiled,context);
const rank=context.exports.rankRepositories;
const baseline=rank(seed.records);
assert.equal(baseline.length,seed.records.filter(r=>!r.exclusion_reason).length);
for(const r of baseline)assert.ok(Math.abs(r.score-r.fri*.9)<1e-9);
const selected=baseline[40];
const one=rank(seed.records,{[selected.repository]:1}).find(r=>r.repository===selected.repository);
assert.ok(one.score>selected.score && one.score-selected.score<2);
const hundred=rank(seed.records,{[selected.repository]:100}).find(r=>r.repository===selected.repository);
const thousand=rank(seed.records,{[selected.repository]:1000}).find(r=>r.repository===selected.repository);
assert.equal(hundred.score,thousand.score);
const penalized={...selected,maintenance_penalty:.25};
assert.ok(Math.abs(rank([penalized],{[selected.repository]:100})[0].score-(rank([{...selected,maintenance_penalty:0}],{[selected.repository]:100})[0].score*.75))<1e-9);
assert.equal(rank(seed.records,{[selected.repository]:0}).find(r=>r.repository===selected.repository).score,selected.score);
console.log('Passed: zero-vote baseline, vote impact, cap, undo and maintenance scoring.');
